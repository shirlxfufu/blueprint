import * as React from "react";
import type { SVGIconProps } from "../../svgIconProps";
import { IconSize } from "../../iconTypes";
import { SVGIconContainer } from "../../svgIconContainer";

export const SymbolCircle: React.FC<SVGIconProps> = React.forwardRef<any, SVGIconProps>((props, ref) => {
    const isLarge = (props.size ?? IconSize.STANDARD) >= IconSize.LARGE;
    const pixelGridSize = isLarge ? IconSize.LARGE : IconSize.STANDARD;
    const translation = `${-1 * pixelGridSize / 0.05 / 2}`;
    const style = { transformOrigin: "center" };
    return (
        <SVGIconContainer iconName="symbol-circle" ref={ref} {...props}>
            <path
                d={isLarge ? "M200 320A120 120 0 1 0 200 80A120 120 0 0 0 200 320" : "M160 260A100 100 0 1 0 160 60A100 100 0 0 0 160 260"}
                fillRule="evenodd"
                transform={`scale(0.05, -0.05) translate(${translation}, ${translation})`}
                style={style}
            />
        </SVGIconContainer>
   );
});
SymbolCircle.displayName = `Blueprint6.Icon.SymbolCircle`;
export default SymbolCircle;
